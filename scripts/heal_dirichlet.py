"""Heal corrupted text with DirichletFM — approach C (localize-then-inpaint).

End-to-end "self-healing" inference on a FROZEN DirichletFM checkpoint, for the
realistic setting where **we do not know which tokens are corrupted**. One
backbone serves two roles (no new network is trained beyond a single linear
head):

  1. LOCALIZE — a per-token linear *energy* head on frozen DirichletFM features
     (the BayesLinHead recipe, ``scripts/ood_bayes_linear.py``): valid char -> E~0,
     corrupt char -> E>=margin. Features are the DETERMINISTIC Dirichlet-mean
     backbone activations at ``t_eval`` (``_perpos_feats``). Per-token energy is
     thresholded into a binary heal-mask; the threshold is calibrated to a target
     false-positive rate on clean tokens, and the headline operating point is
     selected by F1 on the held-out CALIBRATION set (never on the demo).

  2. INPAINT — a masked-Euler integration of the DirichletFM marginal vector
     field (``t: 1 -> t_max``). Trusted (un-flagged) positions are re-imposed
     every step via the deterministic Dirichlet mean concentrated on the observed
     token (RePaint-style known-region conditioning, adapted to the Dirichlet
     path); flagged positions are generated by the field, conditioned on the
     trusted context through the non-causal backbone. Trusted tokens are restored
     verbatim at the end.

The ground-truth corruption mask is used ONLY to *score* the demo result — never
to drive healing or to select the operating point. The demo corruption is
averaged over ``--n-seeds`` independent realizations to give an honest CI.

Headline metrics (per-region, correctly denominated):
  fix_rate     = P(corrupt token -> correct)           [recovery, want high]
  damage_rate  = P(clean token   -> broken)            [collateral, want low]
  net/corrupt  = (fixed - damaged) / n_corrupt          [net tokens recovered per corrupt]
The whole-sequence delta is reported only as a (dilution-dominated) diagnostic:
it equals (fixed - damaged)/(B*L) and is structurally capped near corrupt_rate
because ~(1-corrupt_rate) of positions are restored verbatim.

Honest ceiling: this is character-level text8. Healing moves toward
n-gram-plausible character strings, not toward correct words/meaning. It is a
*mechanism demonstration* of transport-based, OOD-localized healing.

Usage:
    python scripts/heal_dirichlet.py \
        --ckpt runs/sflm_bench_a100_20g_L256_d1280L14_full/DirichletFM/epoch_final.pt \
        --corrupt-rate 0.15 --n-demo 16 --n-seeds 5 --out heal_out/heal.json
"""

