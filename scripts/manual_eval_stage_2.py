def plot_roc_overlay(
    metrics: dict[str, list[torch.Tensor | float]],
    out_dir: Path,
    *,
    kind: str,
) -> None:
    rates = metrics["rates"]
    if kind == "energy":
        pos_list = metrics["energy_invalid"]
        neg_list = metrics["energy_valid"]
        auc_list = metrics["energy_auroc"]
        title = "ROC curves across scramble rates (energy)"
        out_name = "stage2_roc_curves_energy.png"
    elif kind == "variance":
        pos_list = metrics["var_invalid"]
        neg_list = metrics["var_valid"]
        auc_list = metrics["var_auroc"]
        title = "ROC curves across scramble rates (variance)"
        out_name = "stage2_roc_curves_variance.png"
    else:
        raise ValueError(f"Unknown ROC kind: {kind}")

    fig, ax = plt.subplots(figsize=(7, 7))
    cmap = plt.cm.plasma
    colors = [cmap(i / max(len(rates) - 1, 1)) for i in range(len(rates))]

    for rate, pos, neg, auc, color in zip(rates, pos_list, neg_list, auc_list, colors):
        assert isinstance(pos, torch.Tensor)
        assert isinstance(neg, torch.Tensor)
        fpr, tpr = compute_roc_curve(positive_scores=pos, negative_scores=neg)
        ax.plot(
            fpr.numpy(),
            tpr.numpy(),
            color=color,
            alpha=0.85,
            label=f"r={rate:.2f} (AUC={float(auc):.3f})",
        )

    ax.plot([0, 1], [0, 1], "k--", linewidth=1, alpha=0.5, label="random")
    ax.set_xlabel("false positive rate")
    ax.set_ylabel("true positive rate")
    ax.set_title(title)
    ax.grid(True)
    ax.legend(fontsize=8)
    fig.tight_layout()
    out_path = out_dir / out_name
    fig.savefig(out_path, dpi=160)
    plt.close(fig)
    print(f"Saved ROC overlay ({kind}) → {out_path}")


