def plot_score_density_at_rate(
    metrics: dict[str, list[torch.Tensor | float]],
    out_dir: Path,
    target_rate: float,
) -> None:
    """Overlay valid/invalid density in sequence score space (energy vs variance)."""
    rates = [float(r) for r in metrics["rates"]]
    if not rates:
        return
    idx = min(range(len(rates)), key=lambda i: abs(rates[i] - target_rate))
    rate = rates[idx]

    e_valid = metrics["energy_valid"][idx]
    e_invalid = metrics["energy_invalid"][idx]
    v_valid = metrics["var_valid"][idx]
    v_invalid = metrics["var_invalid"][idx]
    assert isinstance(e_valid, torch.Tensor)
    assert isinstance(e_invalid, torch.Tensor)
    assert isinstance(v_valid, torch.Tensor)
    assert isinstance(v_invalid, torch.Tensor)

    ev = e_valid.numpy()
    ei = e_invalid.numpy()
    vv = v_valid.numpy()
    vi = v_invalid.numpy()

    e_all = np.concatenate([ev, ei], axis=0)
    v_all = np.concatenate([vv, vi], axis=0)
    if e_all.size == 0 or v_all.size == 0:
        return

    e_min, e_max = float(e_all.min()), float(e_all.max())
    v_min, v_max = float(v_all.min()), float(v_all.max())
    if e_min == e_max:
        e_pad = max(abs(e_min) * 0.05, 1e-3)
        e_min -= e_pad
        e_max += e_pad
    if v_min == v_max:
        v_pad = max(abs(v_min) * 0.05, 1e-4)
        v_min -= v_pad
        v_max += v_pad

    bins = 32
    h_valid, e_edges, v_edges = np.histogram2d(
        ev,
        vv,
        bins=bins,
        range=[[e_min, e_max], [v_min, v_max]],
        density=True,
    )
    h_invalid, _, _ = np.histogram2d(
        ei,
        vi,
        bins=bins,
        range=[[e_min, e_max], [v_min, v_max]],
        density=True,
    )
    e_centers = 0.5 * (e_edges[:-1] + e_edges[1:])
    v_centers = 0.5 * (v_edges[:-1] + v_edges[1:])

    fig, ax = plt.subplots(figsize=(8, 6))
    plotted_density = False

    if float(h_valid.max()) > 0.0:
        lv = np.linspace(float(h_valid.max()) * 0.20, float(h_valid.max()), 6)
        ax.contourf(
            e_centers,
            v_centers,
            h_valid.T,
            levels=lv,
            cmap="Blues",
            alpha=0.45,
        )
        plotted_density = True
    if float(h_invalid.max()) > 0.0:
        li = np.linspace(float(h_invalid.max()) * 0.20, float(h_invalid.max()), 6)
        ax.contourf(
            e_centers,
            v_centers,
            h_invalid.T,
            levels=li,
            cmap="Reds",
            alpha=0.45,
        )
        plotted_density = True

    # Keep sparse points visible even when density is smooth.
    ax.scatter(ev, vv, s=14, alpha=0.55, color="navy", label="valid")
    ax.scatter(ei, vi, s=14, alpha=0.55, color="darkred", label="invalid")

    if not plotted_density:
        ax.text(
            0.02,
            0.98,
            "Insufficient spread for smooth density; showing points only.",
            transform=ax.transAxes,
            ha="left",
            va="top",
            fontsize=9,
        )

    ax.set_xlabel("sequence energy (token mean)")
    ax.set_ylabel("sequence variance (token mean)")
    ax.set_title(f"Valid vs invalid landing density in score space (rate={rate:.2f})")
    ax.grid(True)
    ax.legend()
    fig.tight_layout()
    out_path = out_dir / "stage2_density_score_space.png"
    fig.savefig(out_path, dpi=170)
    plt.close(fig)
    print(f"Saved score density plot → {out_path}")


def plot_tokenwise_valid_invalid_heatmaps(
    model: torch.nn.Module,
    base_cfg: Config,
    *,
    rate: float,
    n_sequences: int,
    use_train_loader: bool,
    device: torch.device,
    out_dir: Path,
) -> None:
    """Two heatmaps: token energy and token variance for matched valid/invalid pairs."""
    cfg_rate = deepcopy(base_cfg)
    _route_corrupt_rate(cfg_rate, rate)

    valid, invalid, valid_ids, invalid_ids = _load_valid_invalid_pairs_with_ids(
        model=model,
        cfg=cfg_rate,
        n_needed=n_sequences,
        use_train_loader=use_train_loader,
        device=device,
    )
    x_valid = valid.to(device)
    x_invalid = invalid.to(device)

    e_valid_tok, v_valid_tok, _ = model.per_token_uq(x_valid)
    e_invalid_tok, v_invalid_tok, _ = model.per_token_uq(x_invalid)
    # Mark tokens that differ between valid and invalid paired sequences.
    changed_mask = (x_invalid - x_valid).pow(2).sum(dim=-1).sqrt() > 1e-6

    e_valid_np = e_valid_tok.detach().cpu().numpy()
    e_invalid_np = e_invalid_tok.detach().cpu().numpy()
    v_valid_np = v_valid_tok.detach().cpu().numpy()
    v_invalid_np = v_invalid_tok.detach().cpu().numpy()
    changed_np = changed_mask.detach().cpu().numpy()

    n_rows = min(n_sequences, e_valid_np.shape[0], e_invalid_np.shape[0])
    if n_rows == 0:
        return

    seq_labels: list[str] = []
    energy_rows: list[np.ndarray] = []
    var_rows: list[np.ndarray] = []
    changed_rows: list[np.ndarray] = []
    for i in range(n_rows):
        seq_labels.append(f"valid {i}")
        energy_rows.append(e_valid_np[i])
        var_rows.append(v_valid_np[i])
        changed_rows.append(changed_np[i])
        seq_labels.append(f"invalid {i}")
        energy_rows.append(e_invalid_np[i])
        var_rows.append(v_invalid_np[i])
        changed_rows.append(changed_np[i])

    energy_grid = np.stack(energy_rows, axis=0)
    variance_grid = np.stack(var_rows, axis=0)
    changed_grid = np.stack(changed_rows, axis=0)
    text_grid = _build_token_text_grid(
        cfg=cfg_rate,
        valid_ids=valid_ids[:n_rows] if valid_ids is not None else None,
        invalid_ids=invalid_ids[:n_rows] if invalid_ids is not None else None,
        n_rows=n_rows,
        seq_len=energy_grid.shape[1],
    )

    fig, axes = plt.subplots(
        2,
        2,
        figsize=(18, max(9, 0.70 * energy_grid.shape[0])),
        gridspec_kw={"height_ratios": [3.8, 1.8], "hspace": 0.08, "wspace": 0.12},
    )
    ax_e = axes[0, 0]
    ax_v = axes[0, 1]
    ax_e_txt = axes[1, 0]
    ax_v_txt = axes[1, 1]

    im_e = ax_e.imshow(energy_grid, aspect="auto", interpolation="nearest", cmap="coolwarm")
    ax_e.set_title(f"Token energy heatmap (rate={rate:.2f})")
    ax_e.set_xlabel("token position")
    ax_e.set_ylabel("sequence (v=valid, i=invalid)")
    ax_e.set_yticks(np.arange(len(seq_labels)))
    ax_e.set_yticklabels(seq_labels)
    fig.colorbar(im_e, ax=ax_e, fraction=0.046, pad=0.04, label="energy")

    im_v = ax_v.imshow(variance_grid, aspect="auto", interpolation="nearest", cmap="magma")
    ax_v.set_title(f"Token variance heatmap (rate={rate:.2f})")
    ax_v.set_xlabel("token position")
    ax_v.set_ylabel("sequence (v=valid, i=invalid)")
    ax_v.set_yticks(np.arange(len(seq_labels)))
    ax_v.set_yticklabels(seq_labels)
    fig.colorbar(im_v, ax=ax_v, fraction=0.046, pad=0.04, label="variance")

    changed_y, changed_x = np.where(changed_grid)
    if changed_x.size > 0:
        marker_color = "#00C853"  # dark neon green
        for ax in (ax_e, ax_v):
            ax.scatter(
                changed_x,
                changed_y,
                marker="s",
                s=22,
                facecolors="none",
                edgecolors=marker_color,
                linewidths=1.1,
            )
            ax.text(
                0.01,
                0.99,
                "Squares mark tokens changed in invalid sequence.",
                transform=ax.transAxes,
                ha="left",
                va="top",
                fontsize=8,
                bbox={"facecolor": "white", "alpha": 0.65, "edgecolor": "none", "pad": 2.0},
            )

    for ax_txt, title in (
        (ax_e_txt, "Sequence text aligned to token positions"),
        (ax_v_txt, "Sequence text aligned to token positions"),
    ):
        ax_txt.set_facecolor("white")
        ax_txt.set_xlim(-0.5, energy_grid.shape[1] - 0.5)
        ax_txt.set_ylim(energy_grid.shape[0] - 0.5, -0.5)
        ax_txt.set_title(title, fontsize=10)
        ax_txt.set_xlabel("token position")
        ax_txt.set_ylabel("sequence (v=valid, i=invalid)")
        ax_txt.set_yticks(np.arange(len(seq_labels)))
        ax_txt.set_yticklabels(seq_labels)
        ax_txt.set_xticks(np.arange(energy_grid.shape[1]))
        ax_txt.grid(False)
        for y in range(text_grid.shape[0]):
            for x in range(text_grid.shape[1]):
                tok = str(text_grid[y, x])
                if tok:
                    ax_txt.text(
                        x,
                        y,
                        tok,
                        ha="center",
                        va="center",
                        fontsize=7,
                        fontfamily="monospace",
                        color="black",
                    )
        # Draw light row separators to make whitespace bands clear.
        for y in np.arange(-0.5, energy_grid.shape[0], 1.0):
            ax_txt.axhline(y, color="#DDDDDD", linewidth=0.5)

    fig.tight_layout()
    out_path = out_dir / "stage2_tokenwise_valid_invalid_heatmaps.png"
    fig.savefig(out_path, dpi=170)
    plt.close(fig)
    print(f"Saved tokenwise valid/invalid heatmaps → {out_path}")


def main(argv: list[str] | None = None) -> None:
    args = _build_argparser().parse_args(argv)
    seed_all(args.seed)

    out_dir = Path(args.out_dir)
    out_dir.mkdir(parents=True, exist_ok=True)

    cfg = make_smoke_config() if args.smoke else Config()
    if args.smoke:
        cfg.text8_dataset.max_train_windows = 32
        cfg.text8_dataset.max_eval_windows = 32
        cfg.training.num_workers = 0
    apply_training_data_args(cfg, args)
    _apply_llm_topk_probs_overrides(cfg, args)
    device = torch.device(cfg.training.device)

    cfg_eval = deepcopy(cfg)
    cfg_eval.training = replace(cfg_eval.training, model_name="bayesian_auditor_stage2")
    model = build_model(cfg_eval)

    stage1_ckpt = Path(args.stage1_backbone_ckpt)
    stage2_ckpt = Path(args.checkpoint)
    if not stage1_ckpt.is_file():
        raise FileNotFoundError(f"Stage-1 checkpoint not found: {stage1_ckpt}")
    if not stage2_ckpt.is_file():
        raise FileNotFoundError(f"Stage-2 checkpoint not found: {stage2_ckpt}")

    stage1_state = _checkpoint_state_dict(stage1_ckpt, device)
    _load_stage1_backbone_into_stage2(model, stage1_state)
    print(f"Loaded Stage-1 backbone/projection: {stage1_ckpt}")

    stage2_state = _checkpoint_state_dict(stage2_ckpt, device)
    _load_stage2_head_only(model, stage2_state)
    print(f"Loaded Stage-2 head/GP: {stage2_ckpt}")

    model = model.to(device)
    model.eval()

    metrics = eval_rate_sweep(
        model=model,
        base_cfg=cfg,
        scramble_rates=args.scramble_rates,
        n_samples=args.n_score_samples,
        use_train_loader=args.use_train_loader,
        device=device,
    )

    plot_energy_vs_rate(metrics, out_dir=out_dir)
    plot_variance_vs_rate(metrics, out_dir=out_dir)
    plot_auroc_vs_rate(metrics, out_dir=out_dir)
    plot_roc_overlay(metrics, out_dir=out_dir, kind="energy")
    plot_roc_overlay(metrics, out_dir=out_dir, kind="variance")

    if args.distribution_rate >= 0.0:
        plot_single_rate_distributions(metrics, out_dir=out_dir, target_rate=args.distribution_rate)
        plot_score_density_at_rate(metrics, out_dir=out_dir, target_rate=args.distribution_rate)
        plot_tokenwise_valid_invalid_heatmaps(
            model=model,
            base_cfg=cfg,
            rate=args.distribution_rate,
            n_sequences=args.token_heatmap_sequences,
            use_train_loader=args.use_train_loader,
            device=device,
            out_dir=out_dir,
        )

    print("\nDone. All Stage-2 evaluation plots saved to:", out_dir)


if __name__ == "__main__":
    main()
