def _route_corrupt_rate(cfg: Config, rate: float) -> None:
    source = cfg.training_data.source
    if source == "llm_topk_probs":
        cfg.llm_topk_probs.corrupt_rate = rate
    elif source == "llm_topk":
        cfg.llm_embedding_dataset.corrupt_rate = rate
    elif source in ("dna",):
        cfg.dna_dataset.train_corrupt_rate = rate
        cfg.dna_dataset.eval_corrupt_rate = rate
    elif source in ("medical",):
        cfg.medical_dataset.train_corrupt_rate = rate
        cfg.medical_dataset.eval_corrupt_rate = rate
    else:
        cfg.text8_dataset.train_corrupt_rate = rate
        cfg.text8_dataset.eval_corrupt_rate = rate


def _checkpoint_state_dict(path: Path, device: torch.device) -> dict[str, torch.Tensor]:
    ckpt = torch.load(path, map_location=device)
    if isinstance(ckpt, dict) and "model_state_dict" in ckpt:
        state = ckpt["model_state_dict"]
        if not isinstance(state, dict):
            raise ValueError(f"'model_state_dict' in checkpoint is not a mapping: {path}")
        return dict(state)
    if isinstance(ckpt, dict):
        return dict(ckpt)
    raise ValueError(f"Unsupported checkpoint format at {path}")


def _filter_prefix(state: dict[str, torch.Tensor], prefix: str) -> dict[str, torch.Tensor]:
    return {k: v for k, v in state.items() if k.startswith(prefix)}


def _load_stage1_backbone_into_stage2(
    stage2_model: torch.nn.Module, stage1_state: dict[str, torch.Tensor]
) -> None:
    backbone_state = _filter_prefix(stage1_state, "backbone.")
    if not backbone_state:
        raise ValueError("Stage-1 checkpoint has no 'backbone.*' keys.")
    missing_backbone, _unexpected_backbone = stage2_model.backbone.load_state_dict(  # type: ignore[attr-defined]
        {k.removeprefix("backbone."): v for k, v in backbone_state.items()},
        strict=False,
    )
    if missing_backbone:
        raise RuntimeError(
            f"Missing backbone keys while loading Stage-1 into Stage-2: {sorted(missing_backbone)}"
        )

    stage1_proj = _filter_prefix(stage1_state, "llm_projection.")
    if stage1_proj and getattr(stage2_model, "llm_projection", None) is not None:
        missing_proj, _unexpected_proj = stage2_model.llm_projection.load_state_dict(  # type: ignore[attr-defined]
            {k.removeprefix("llm_projection."): v for k, v in stage1_proj.items()},
            strict=False,
        )
        if missing_proj:
            raise RuntimeError(
                "Missing llm_projection keys while loading Stage-1 into Stage-2: "
                f"{sorted(missing_proj)}"
            )


def _load_stage2_head_only(
    stage2_model: torch.nn.Module, stage2_state: dict[str, torch.Tensor]
) -> None:
    # Keep backbone/projection from Stage 1 and load only trainable Stage-2 modules.
    head_state = {
        k: v for k, v in stage2_state.items() if k.startswith("latent_head.") or k.startswith("gp.")
    }
    if not head_state:
        raise ValueError("Stage-2 checkpoint has no 'latent_head.*' or 'gp.*' keys.")
    missing, unexpected = stage2_model.load_state_dict(head_state, strict=False)
    missing_bad = [k for k in missing if k.startswith("latent_head.") or k.startswith("gp.")]
    unexpected_bad = [k for k in unexpected if k.startswith("latent_head.") or k.startswith("gp.")]
    if missing_bad:
        raise RuntimeError(f"Missing Stage-2 head keys: {sorted(missing_bad)}")
    if unexpected_bad:
        raise RuntimeError(f"Unexpected Stage-2 head keys: {sorted(unexpected_bad)}")


def _load_valid_invalid_pairs(
    model: torch.nn.Module,
    cfg: Config,
    n_needed: int,
    use_train_loader: bool,
    device: torch.device,
) -> tuple[torch.Tensor, torch.Tensor]:
    datamodule, _ = build_training_datamodule(cfg)

    loader = None
    if not use_train_loader:
        val_fn = getattr(datamodule, "val_dataloader", None)
        if callable(val_fn):
            try:
                loader = val_fn()
                print("Using validation dataloader.")
            except Exception as e:  # pragma: no cover - fallback path
                print(f"val_dataloader() failed ({e}), falling back to train loader.")
                loader = None

    if loader is None:
        loader = datamodule.train_dataloader()
        if not use_train_loader:
            print(
                "Warning: no validation loader found, using training data. "
                "Pass --use-train-loader to silence."
            )

    all_valid: list[torch.Tensor] = []
    all_invalid: list[torch.Tensor] = []
    collected = 0
    for batch in loader:
        batch = to_device(batch, str(device))
        batch = model.prepare_batch(batch)
        if "log_x_invalid" not in batch:
            raise ValueError(
                "Batch is missing 'log_x_invalid'. Stage-2 scramble evaluation "
                "requires a datasource that emits valid/invalid pairs."
            )
        valid = batch["log_x"]
        invalid = batch["log_x_invalid"]
        all_valid.append(valid)
        all_invalid.append(invalid)
        collected += valid.shape[0]
        if collected >= n_needed:
            break

    valid_out = torch.cat(all_valid, dim=0)[:n_needed]
    invalid_out = torch.cat(all_invalid, dim=0)[:n_needed]
    return valid_out, invalid_out


def _load_valid_invalid_pairs_with_ids(
    model: torch.nn.Module,
    cfg: Config,
    n_needed: int,
    use_train_loader: bool,
    device: torch.device,
) -> tuple[torch.Tensor, torch.Tensor, torch.Tensor | None, torch.Tensor | None]:
    datamodule, _ = build_training_datamodule(cfg)

    loader = None
    if not use_train_loader:
        val_fn = getattr(datamodule, "val_dataloader", None)
        if callable(val_fn):
            try:
                loader = val_fn()
                print("Using validation dataloader.")
            except Exception as e:  # pragma: no cover - fallback path
                print(f"val_dataloader() failed ({e}), falling back to train loader.")
                loader = None

    if loader is None:
        loader = datamodule.train_dataloader()
        if not use_train_loader:
            print(
                "Warning: no validation loader found, using training data. "
                "Pass --use-train-loader to silence."
            )

    all_valid: list[torch.Tensor] = []
    all_invalid: list[torch.Tensor] = []
    all_ids: list[torch.Tensor] = []
    all_ids_invalid: list[torch.Tensor] = []
    collected = 0
    have_ids = True
    have_ids_invalid = True

    for batch in loader:
        batch = to_device(batch, str(device))
        batch = model.prepare_batch(batch)
        if "log_x_invalid" not in batch:
            raise ValueError(
                "Batch is missing 'log_x_invalid'. Stage-2 scramble evaluation "
                "requires a datasource that emits valid/invalid pairs."
            )
        valid = batch["log_x"]
        invalid = batch["log_x_invalid"]
        all_valid.append(valid)
        all_invalid.append(invalid)

        if have_ids:
            ids = batch.get("token_ids")
            if torch.is_tensor(ids):
                all_ids.append(ids.detach().cpu())
            else:
                have_ids = False
        if have_ids_invalid:
            ids_invalid = batch.get("token_ids_invalid")
            if torch.is_tensor(ids_invalid):
                all_ids_invalid.append(ids_invalid.detach().cpu())
            else:
                have_ids_invalid = False

        collected += valid.shape[0]
        if collected >= n_needed:
            break

    valid_out = torch.cat(all_valid, dim=0)[:n_needed]
    invalid_out = torch.cat(all_invalid, dim=0)[:n_needed]

    ids_out: torch.Tensor | None = None
    ids_invalid_out: torch.Tensor | None = None
    if have_ids and all_ids:
        ids_out = torch.cat(all_ids, dim=0)[:n_needed]
    if have_ids_invalid and all_ids_invalid:
        ids_invalid_out = torch.cat(all_ids_invalid, dim=0)[:n_needed]
    return valid_out, invalid_out, ids_out, ids_invalid_out


def _token_label_from_id(cfg: Config, token_id: int) -> str:
    source = cfg.training_data.source
    if source == "raw_text":
        if 0 <= token_id < len(TEXT8_ALPHABET):
            return TEXT8_ALPHABET[token_id]
        return "?"
    if source == "dna":
        alphabet = DNA_ALPHABET_N if cfg.dna_dataset.use_n_base else DNA_ALPHABET
        if 0 <= token_id < len(alphabet):
            return alphabet[token_id]
        return "?"
    if source == "medical":
        if 0 <= token_id < len(_CLINICAL_CHARS):
            return _CLINICAL_CHARS[token_id]
        return "?"
    # Fallback for LLM-token datasets: keep ids readable but compact.
    return str(token_id)


def _build_token_text_grid(
    cfg: Config,
    valid_ids: torch.Tensor | None,
    invalid_ids: torch.Tensor | None,
    n_rows: int,
    seq_len: int,
) -> np.ndarray:
    grid = np.full((2 * n_rows, seq_len), "", dtype=object)
    if valid_ids is None or invalid_ids is None:
        grid[:, :] = "·"
        return grid
    v_np = valid_ids.numpy()
    i_np = invalid_ids.numpy()
    for i in range(n_rows):
        for t in range(seq_len):
            grid[2 * i, t] = _token_label_from_id(cfg, int(v_np[i, t]))
            grid[2 * i + 1, t] = _token_label_from_id(cfg, int(i_np[i, t]))
    return grid


def _sequence_energy_variance(
    model: torch.nn.Module,
    log_x: torch.Tensor,
) -> tuple[torch.Tensor, torch.Tensor]:
    energy_tok, var_tok, _noise_var = model.per_token_uq(log_x)
    return energy_tok.mean(dim=1).cpu(), var_tok.mean(dim=1).cpu()


def compute_auroc(positive_scores: torch.Tensor, negative_scores: torch.Tensor) -> float:
    pos = positive_scores.reshape(-1).float()
    neg = negative_scores.reshape(-1).float()
    if pos.numel() == 0 or neg.numel() == 0:
        return float("nan")
    gt = (pos[:, None] > neg[None, :]).float().mean()
    eq = (pos[:, None] == neg[None, :]).float().mean()
    return float((gt + 0.5 * eq).item())


def compute_roc_curve(
    positive_scores: torch.Tensor, negative_scores: torch.Tensor
) -> tuple[torch.Tensor, torch.Tensor]:
    pos = positive_scores.reshape(-1).float()
    neg = negative_scores.reshape(-1).float()
    scores = torch.cat([pos, neg])
    labels = torch.cat([torch.ones_like(pos), torch.zeros_like(neg)])

    thresholds = torch.unique(scores).sort(descending=True).values
    thresholds = torch.cat(
        [
            torch.tensor([float("inf")]),
            thresholds,
            torch.tensor([float("-inf")]),
        ]
    )

    pos_count = labels.sum()
    neg_count = (1.0 - labels).sum()
    tprs, fprs = [], []
    for thr in thresholds:
        pred_pos = (scores >= thr).float()
        tp = (pred_pos * labels).sum()
        fp = (pred_pos * (1.0 - labels)).sum()
        tprs.append(tp / pos_count if pos_count > 0 else torch.tensor(0.0))
        fprs.append(fp / neg_count if neg_count > 0 else torch.tensor(0.0))
    return torch.stack(fprs), torch.stack(tprs)


def _mean_std(x: torch.Tensor) -> tuple[float, float]:
    return float(x.mean().item()), float(x.std().item())


def eval_rate_sweep(
    model: torch.nn.Module,
    base_cfg: Config,
    *,
    scramble_rates: list[float],
    n_samples: int,
    use_train_loader: bool,
    device: torch.device,
) -> dict[str, list[torch.Tensor | float]]:
    rates = sorted(scramble_rates)
    result: dict[str, list[torch.Tensor | float]] = {
        "rates": rates,
        "energy_valid": [],
        "energy_invalid": [],
        "var_valid": [],
        "var_invalid": [],
        "energy_auroc": [],
        "var_auroc": [],
        "energy_valid_mean": [],
        "energy_valid_std": [],
        "energy_invalid_mean": [],
        "energy_invalid_std": [],
        "var_valid_mean": [],
        "var_valid_std": [],
        "var_invalid_mean": [],
        "var_invalid_std": [],
    }

    print("\n--- Stage-2 Scramble-Rate Sweep ---")
    print(
        f"{'rate':>8}  {'AUC_E':>8}  {'AUC_V':>8}  "
        f"{'muE_valid':>10}  {'muE_invalid':>12}  {'muV_valid':>10}  {'muV_invalid':>12}"
    )
    print("-" * 86)

    for rate in tqdm(rates, desc="scramble-rate sweep"):
        cfg_rate = deepcopy(base_cfg)
        _route_corrupt_rate(cfg_rate, rate)

        valid, invalid = _load_valid_invalid_pairs(
            model=model,
            cfg=cfg_rate,
            n_needed=n_samples,
            use_train_loader=use_train_loader,
            device=device,
        )
        x_valid = valid.to(device)
        x_invalid = invalid.to(device)

        e_valid, v_valid = _sequence_energy_variance(model, x_valid)
        e_invalid, v_invalid = _sequence_energy_variance(model, x_invalid)

        e_auc = compute_auroc(positive_scores=e_invalid, negative_scores=e_valid)
        v_auc = compute_auroc(positive_scores=v_invalid, negative_scores=v_valid)

        mu_ev, std_ev = _mean_std(e_valid)
        mu_ei, std_ei = _mean_std(e_invalid)
        mu_vv, std_vv = _mean_std(v_valid)
        mu_vi, std_vi = _mean_std(v_invalid)

        print(
            f"{rate:>8.2f}  {e_auc:>8.4f}  {v_auc:>8.4f}  "
            f"{mu_ev:>10.3f}  {mu_ei:>12.3f}  {mu_vv:>10.6f}  {mu_vi:>12.6f}"
        )

        result["energy_valid"].append(e_valid)
        result["energy_invalid"].append(e_invalid)
        result["var_valid"].append(v_valid)
        result["var_invalid"].append(v_invalid)
        result["energy_auroc"].append(e_auc)
        result["var_auroc"].append(v_auc)
        result["energy_valid_mean"].append(mu_ev)
        result["energy_valid_std"].append(std_ev)
        result["energy_invalid_mean"].append(mu_ei)
        result["energy_invalid_std"].append(std_ei)
        result["var_valid_mean"].append(mu_vv)
        result["var_valid_std"].append(std_vv)
        result["var_invalid_mean"].append(mu_vi)
        result["var_invalid_std"].append(std_vi)

    return result


def plot_energy_vs_rate(metrics: dict[str, list[torch.Tensor | float]], out_dir: Path) -> None:
    rates = metrics["rates"]
    ev_m = metrics["energy_valid_mean"]
    ev_s = metrics["energy_valid_std"]
    ei_m = metrics["energy_invalid_mean"]
    ei_s = metrics["energy_invalid_std"]

    fig, ax = plt.subplots(figsize=(8, 5))
    ax.plot(rates, ev_m, "o-", color="steelblue", label="valid mean energy")
    ax.fill_between(
        rates,
        [m - s for m, s in zip(ev_m, ev_s)],
        [m + s for m, s in zip(ev_m, ev_s)],
        color="steelblue",
        alpha=0.2,
    )
    ax.plot(rates, ei_m, "o-", color="tomato", label="invalid mean energy")
    ax.fill_between(
        rates,
        [m - s for m, s in zip(ei_m, ei_s)],
        [m + s for m, s in zip(ei_m, ei_s)],
        color="tomato",
        alpha=0.2,
    )
    ax.set_xlabel("scramble/corruption rate")
    ax.set_ylabel("sequence energy (token mean)")
    ax.set_title("Stage-2 energy vs scramble rate")
    ax.grid(True)
    ax.legend()
    fig.tight_layout()
    out_path = out_dir / "stage2_energy_vs_rate.png"
    fig.savefig(out_path, dpi=160)
    plt.close(fig)
    print(f"Saved energy-vs-rate plot → {out_path}")


