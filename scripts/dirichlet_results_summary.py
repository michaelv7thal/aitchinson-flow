"""End-to-end results summary for the Dirichlet capstone.

Reads every ``runs/dphase{N}_*`` directory + the unigram baseline + the
existing baseline_5ep reference, and emits a markdown report on stdout
(or to ``--out``). The columns are the metrics the capstone hangs on:
flow_loss, γ-buckets, KL_uni/bi/tri, H_ratio.

Usage:
    python scripts/dirichlet_results_summary.py --out RESULTS_DIRICHLET.md
"""

from __future__ import annotations

import argparse
import json
import math
from pathlib import Path

METRICS_TRAIN = ("flow_loss", "ce", "g<.33", "g<.66", "g<1", "loss")
METRICS_EVAL = ("unigram_kl", "bigram_kl", "trigram_kl", "H_gen", "H_gt", "H_ratio")


def _last_history_row(run_dir: Path) -> dict[str, float]:
    p = run_dir / "history.jsonl"
    if not p.exists():
        return {}
    rows = [json.loads(line) for line in p.read_text().strip().splitlines() if line.strip()]
    return rows[-1] if rows else {}


def _eval_dict(run_dir: Path) -> dict:
    p = run_dir / "eval.json"
    return json.loads(p.read_text()) if p.exists() else {}


def _pull(run_dir: Path) -> dict[str, float]:
    h = _last_history_row(run_dir)
    e = _eval_dict(run_dir)
    out: dict[str, float] = {}
    for k in METRICS_TRAIN:
        if k in h:
            out[k] = float(h[k])
    for k in METRICS_EVAL:
        if k in e:
            out[k] = float(e[k])
    if "H_ratio" not in out and "H_gen" in out and "H_gt" in out and out["H_gt"]:
        out["H_ratio"] = out["H_gen"] / out["H_gt"]
    out["samples"] = e.get("samples", [])
    return out


def _fmt(v: float | None) -> str:
    if v is None or (isinstance(v, float) and math.isnan(v)):
        return "—"
    if abs(v) < 1e-3:
        return f"{v:.2e}"
    return f"{v:.4f}"


def _table(rows: list[tuple[str, dict[str, float]]], cols: tuple[str, ...]) -> str:
    if not rows:
        return "_(no rows)_\n"
    width_name = max(len(n) for n, _ in rows + [("run", {})])
    width_col = max((len(c) for c in cols), default=0)
    width_col = max(width_col, 10)

    out = []
    out.append("| " + "run".ljust(width_name) + " | "
               + " | ".join(c.rjust(width_col) for c in cols) + " |")
    out.append("|" + "-" * (width_name + 2) + "|"
               + "|".join("-" * (width_col + 2) for _ in cols) + "|")
    for name, r in rows:
        cells = [_fmt(r.get(c)) for c in cols]
        out.append("| " + name.ljust(width_name) + " | "
                   + " | ".join(c.rjust(width_col) for c in cells) + " |")
    return "\n".join(out) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__)
    ap.add_argument("--runs-root", type=str, default="runs")
    ap.add_argument("--out", type=str, default=None,
                    help="markdown output path; '-' or unset prints to stdout")
    args = ap.parse_args()

    root = Path(args.runs_root)
    candidates = sorted([d for d in root.iterdir() if d.is_dir()])

    groups: dict[str, list[Path]] = {
        "Reference": [], "Phase 3": [], "Phase 4": [], "Phase 5": [], "Phase 6": [],
    }
    for d in candidates:
        n = d.name
        if n in {"baseline_5ep", "unigram_baseline"}:
            groups["Reference"].append(d)
        elif n.startswith("dphase3"):
            groups["Phase 3"].append(d)
        elif n.startswith("dphase4"):
            groups["Phase 4"].append(d)
        elif n.startswith("dphase5"):
            groups["Phase 5"].append(d)
        elif n.startswith("dphase6"):
            groups["Phase 6"].append(d)

    md: list[str] = []
    md.append("# Dirichlet capstone — results summary\n")
    md.append("Generated by `scripts/dirichlet_results_summary.py`. Calibration "
              "details and Phase-0 diagnostics: `scripts/check_dirichlet_data.py`.\n")

    md.append("## Training endpoints (last `history.jsonl` row)\n")
    for label, dirs in groups.items():
        if not dirs:
            continue
        rows = [(d.name, _pull(d)) for d in dirs]
        md.append(f"### {label}\n")
        md.append(_table(rows, METRICS_TRAIN))

    md.append("## Generation evaluation (`eval.json`)\n")
    for label, dirs in groups.items():
        if not dirs:
            continue
        rows = [(d.name, _pull(d)) for d in dirs]
        md.append(f"### {label}\n")
        md.append(_table(rows, METRICS_EVAL))

    md.append("## Decoded samples (first 8 per run)\n")
    for label, dirs in groups.items():
        if not dirs:
            continue
        for d in dirs:
            data = _pull(d)
            samples = data.get("samples", [])
            if not samples:
                continue
            md.append(f"### {d.name}\n")
            md.append("```\n" + "\n".join(samples[:8]) + "\n```\n")

    text = "\n".join(md) + "\n"
    if args.out and args.out != "-":
        Path(args.out).parent.mkdir(parents=True, exist_ok=True)
        Path(args.out).write_text(text)
        print(f"Wrote {args.out}")
    else:
        print(text)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
